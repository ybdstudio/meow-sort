#!/usr/bin/env node
/* Pre-generates procedural levels offline so the device never runs the
   level generator (40 attempts x 40k solver nodes) on the main thread.
   Usage: node tools/gen_levels.js [count=60]   -> writes js/levels_gen.js */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const count = parseInt(process.argv[2] || '60', 10);
const sb = {};
vm.createContext(sb);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'js/config.js'), 'utf8') + '\n' +
  fs.readFileSync(path.join(ROOT, 'js/core.js'), 'utf8') + '\nthis.CORE = CORE;', sb);
const CORE = sb.CORE, out = {}, t0 = Date.now();
const rule = CORE.CONFIG.accessRule;
for (let n = CORE.LEVELS.length; n < CORE.LEVELS.length + count; n++) {
  const def = CORE.generateLevel(n, rule);
  if (!def.verified) { console.warn('level', n + 1, 'fell back to a hand-made level'); continue; }
  // double-check with a big budget
  const res = CORE.solve(CORE.buildBoard(def), rule, 300000);
  if (!res.solved) { console.warn('level', n + 1, 'not re-verified, skipped'); continue; }
  out[n] = { name: def.name, beds: def.beds, left: def.left, right: def.right, verified: { rule, moves: res.moves.length } };
}
const body = '/* AUTO-GENERATED by tools/gen_levels.js — do not edit. Index = level index (0-based). */\n' +
  'var PREGEN_LEVELS = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(ROOT, 'js/levels_gen.js'), body);
console.log('wrote', Object.keys(out).length, 'levels in', Date.now() - t0, 'ms');
